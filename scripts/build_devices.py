def page_head(src, title, desc, url):
    head_end = src.index("</head>")
    head = src[:head_end]
    head = re.sub(r"<title>.*?</title>", "<title>%s</title>" % esc(title), head, count=1, flags=re.S)
    head = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % esc(desc), head, count=1)
    head = head.replace("https://jeeinclinic.com/clinic/parking/", url)
    head = re.sub(r"\n  /\* DIAG:START \*/.*?/\* DIAG:END \*/", "", head, flags=re.S)
    head = re.sub(r"\n  /\* DEV:START \*/.*?/\* DEV:END \*/", "", head, flags=re.S)
    head = head.replace("</style>", "  /* DEV:START */" + bf.CSS + EXTRA_CSS + "  /* DEV:END */\n</style>", 1)
    return head, src[head_end + len("</head>"):]


